// Writes src/lib/clock12.ts: the time zones of the countries whose preferred clock is 12 h in CLDR.
// Run on a machine with tzdata: node scripts/clock12.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const url =
  'https://raw.githubusercontent.com/unicode-org/cldr-json/49.0.0/cldr-json/cldr-core/supplemental/timeData.json'
const time = (await (await fetch(url)).json()).supplemental.timeData
const h12 = new Set(Object.keys(time).filter((k) => /^[A-Z]{2}$/.test(k) && time[k]._preferred.startsWith('h')))
const rows = readFileSync('/usr/share/zoneinfo/zone.tab', 'utf8')
  .split('\n')
  .filter((l) => l && l[0] !== '#')
  .map((l) => l.split('\t'))
const country = new Map(rows.map(([c, , z]) => [z, c]))
const links = readFileSync('/usr/share/zoneinfo/tzdata.zi', 'utf8')
  .split('\n')
  .map((l) => l.split(' '))
  .filter(([k]) => k === 'L')
// Chrome reports ICU's names (Asia/Calcutta), Firefox and Safari IANA's (Asia/Kolkata).
for (const z of Intl.supportedValuesOf('timeZone')) {
  if (country.has(z)) continue
  const target = links.find((l) => l[2] === z)?.[1]
  if (!country.has(target)) throw new Error(`no country for ${z}`)
  country.set(z, country.get(target))
}
const zones = [...country]
  .filter(([, c]) => h12.has(c))
  .map(([z]) => z)
  .sort()
  .join(' ')
writeFileSync(
  new URL('../src/lib/clock12.ts', import.meta.url),
  `// Generated by scripts/clock12.mjs from CLDR timeData and tzdata.\nexport const H12 =\n  ' ${zones} '\n`,
)
