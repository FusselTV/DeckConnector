"""Signed firmware images (.dbfw), header layout in firmware/components/db_ota/db_ota.c.

dbfw keygen                       new signing key in ~/.config/deckbridge/ota_key.pem, public key into firmware
dbfw pack --target p4|c6 --version V IN OUT   sign a firmware binary
dbfw info FILE                    show the header
"""

import argparse
import hashlib
import re
import struct
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature, encode_dss_signature

MAGIC = b"DBFW"
FORMAT = 1
TARGETS = {"p4": 1, "c6": 2, "web": 3, "bootloader": 4, "ptable": 5}  # web: level holds api_min
HEADER = struct.Struct("<4sBBHI32s32s")  # signed part, 76 bytes
HEADER_LEN = 144
KEY = Path.home() / ".config/deckbridge/ota_key.pem"
PUBKEY_C = Path(__file__).resolve().parents[2] / "firmware/components/db_ota/ota_pubkey.c"
OTA_C = PUBKEY_C.with_name("db_ota.c")
PAGE = OTA_C.parents[3] / "web/dist/index.html"


def web_api() -> int:
    """The API version of the firmware in this tree: a page packed here needs at least that one."""
    text = (OTA_C.parents[1] / "db_web/include/db_web.h").read_text()
    return int(re.search(r"#define DB_WEB_API (\d+)", text)[1])


def web_image(key) -> bytes:
    """The page the firmware build embeds (web/dist/index.html), gzipped, signed for www."""
    import gzip
    import subprocess

    page = PAGE.read_bytes()
    # no tag names: "web v0.1.0-123-g9e9fe25-dirty" and the page hash would not fit the 31 byte version
    rev = subprocess.run(
        ["git", "describe", "--always", "--dirty", "--exclude=*"], capture_output=True, text=True, cwd=OTA_C.parent
    )
    version = f"web {rev.stdout.strip()} {hashlib.sha256(page).hexdigest()[:6]}"
    return build("web", gzip.compress(page, 9, mtime=0), version, key, web_api())


def security_level() -> int:
    return int(re.search(r"#define SECURITY_LEVEL (\d+)", OTA_C.read_text())[1])


def keygen(_args) -> None:
    if KEY.exists():
        sys.exit(f"{KEY} exists, refusing to replace it")
    key = ec.generate_private_key(ec.SECP256R1())
    KEY.parent.mkdir(parents=True, exist_ok=True)
    KEY.touch(mode=0o600)
    KEY.write_bytes(
        key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    )
    write_pubkey(key.public_key())
    print(f"private key {KEY}, public key {PUBKEY_C}")


def write_pubkey(pub) -> None:
    raw = pub.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    body = ", ".join(f"0x{b:02x}" for b in raw)
    PUBKEY_C.write_text(
        "/* Generated by tools/dbtools/dbfw.py keygen. Verifies signed updates. */\n"
        '#include "ota_pubkey.h"\n\n'
        f"const uint8_t db_ota_pubkey[65] = {{{body}}};\n"
    )


def build(target: str, payload: bytes, version: str, key, level: int | None = None) -> bytes:
    if target not in TARGETS:
        raise ValueError(f"unknown target {target!r}, expected one of {list(TARGETS)}")
    if len(version.encode()) > 31:  # the header keeps 31 bytes and a NUL
        raise ValueError(f"version {version!r} is longer than 31 bytes")
    head = HEADER.pack(
        MAGIC,
        FORMAT,
        TARGETS[target],
        security_level() if level is None else level,
        len(payload),
        version.encode(),
        hashlib.sha256(payload).digest(),
    )
    der = key.sign(head, ec.ECDSA(hashes.SHA256()))
    r, s = decode_dss_signature(der)
    sig = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    return (head + sig).ljust(HEADER_LEN, b"\0") + payload


def pack(args) -> None:
    key = serialization.load_pem_private_key(KEY.read_bytes(), None)
    data = build(args.target, Path(args.input).read_bytes(), args.version, key)
    Path(args.output).write_bytes(data)
    print(f"{args.output}: {args.target} {args.version}, {len(data)} bytes")


def parse(data: bytes, pub=None) -> dict:
    magic, fmt, target, level, length, version, digest = HEADER.unpack_from(data)
    if magic != MAGIC or fmt != FORMAT:
        raise ValueError("not a dbfw image")
    names = {v: k for k, v in TARGETS.items()}
    if target not in names:
        raise ValueError(f"unknown target {target} in the header")
    info = {
        "target": names[target],
        "level": level,
        "length": length,
        "version": version.rstrip(b"\0").decode(),
        "hash_ok": hashlib.sha256(data[HEADER_LEN:]).digest() == digest,
    }
    if pub:
        sig = data[HEADER.size : HEADER.size + 64]
        der = encode_dss_signature(int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big"))
        pub.verify(der, data[: HEADER.size], ec.ECDSA(hashes.SHA256()))
        info["signature_ok"] = True
    return info


def info(args) -> None:
    key = serialization.load_pem_private_key(KEY.read_bytes(), None) if KEY.exists() else None
    print(parse(Path(args.file).read_bytes(), key.public_key() if key else None))


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(required=True)
    sub.add_parser("keygen").set_defaults(fn=keygen)
    p = sub.add_parser("pack")
    p.add_argument("--target", choices=TARGETS, required=True)
    p.add_argument("--version", required=True)
    p.add_argument("input")
    p.add_argument("output")
    p.set_defaults(fn=pack)
    i = sub.add_parser("info")
    i.add_argument("file")
    i.set_defaults(fn=info)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
