"""Generate firmware/components/db_ui/font_data.c: anti-aliased 4 bit glyphs from DejaVu Sans."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = [
    ("small", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 15),
    ("medium", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 21),
    ("large", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 40),
]
CHARS = [chr(c) for c in range(32, 127)] + list("ÄÖÜäöüß°–…·✓✗")
OUT = Path(__file__).resolve().parents[2] / "firmware/components/db_ui/font_data.c"


def render(path: str, size: int):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in CHARS:
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w, h = max(0, right - left), max(0, bottom - top)
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        px = img.tobytes()
        offset = len(data)
        nibbles = [v >> 4 for v in px[: w * h]]
        if len(nibbles) % 2:
            nibbles.append(0)
        data += bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
        glyphs.append((ord(ch), w, h, left, top, round(font.getlength(ch)), offset))
    return ascent, descent, glyphs, data


def main() -> None:
    out = [
        "/* Generated by tools/dbtools/gen_font.py from DejaVu Sans (Bitstream Vera license). Do not edit. */",
        '#include "font.h"',
        "",
    ]
    for name, path, size in FONTS:
        ascent, descent, glyphs, data = render(path, size)
        out.append(f"static const uint8_t {name}_bits[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
        out.append("};")
        out.append(f"static const ui_glyph_t {name}_glyphs[] = {{")
        out += [f"    {{{c}, {w}, {h}, {x}, {y}, {a}, {o}}}," for c, w, h, x, y, a, o in glyphs]
        out.append("};")
        out.append(
            f"const ui_font_t ui_font_{name} = {{{ascent}, {descent}, {len(glyphs)}, {name}_glyphs, {name}_bits}};"
        )
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
