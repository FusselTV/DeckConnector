"""Generate firmware/components/db_ui/font_data.c and icons.h: anti-aliased 4 bit glyphs from DejaVu Sans and
Lucide, the icons of the web page. Usage: gen_font.py <lucide.ttf> <dir with DejaVuSansCondensed.ttf>
(npm pack lucide-static@1.71.0, the web's lucide-react version, and dejavu-fonts-ttf@2.37.3), then clang-format."""

import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = [
    ("small", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 15),
    ("label", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 16),
    ("medium", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 21),
    ("title", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 28),
    ("large", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 40),
    # narrow fallbacks, so an IP address fits on a key
    ("narrow", "{condensed}/DejaVuSansCondensed.ttf", 14),
    ("narrow_small", "{condensed}/DejaVuSansCondensed.ttf", 13),
    ("tiny", "{condensed}/DejaVuSansCondensed.ttf", 11),
]
CHARS = [chr(c) for c in range(32, 127)] + list("ÄÖÜäöüß–…·›„“→")
# Lucide name -> macro name, the web page's icon for the same thing; the icons get code points from U+E000 on
ICONS = {
    "server": "SERVER",
    "radio": "COMPANION",
    "monitor": "APP",
    "settings": "SETTINGS",
    "x": "CLOSE",
    "chevron-right": "OPEN",
    "ethernet-port": "LAN",
    "wifi": "WLAN",
    "wifi-off": "WLAN_OFF",
    "globe": "WEB",
    "router": "SETUP_AP",
    "rotate-cw": "RESTART",
    "rotate-ccw": "RESET",
    "sun": "BRIGHTNESS",
    "cpu": "FIRMWARE",
    "network": "IP",
    "save": "SAVE",
    "download": "UPDATE",
    "triangle-alert": "ALERT",
    "unplug": "NO_NETWORK",
    "key-round": "PASSWORD",
    "refresh-cw": "DHCP",
    "pin": "FIXED",
    "languages": "LANG",
}
ICON_FONTS = [("icon", 50), ("icon_mid", 34), ("icon_small", 22)]
HERE = Path(__file__).resolve().parents[2] / "firmware/components/db_ui"
OUT = HERE / "font_data.c"


def render(path: str, size: int, chars=None):
    """`chars` is a list of (code point in the table, character in the font)."""
    font = ImageFont.truetype(path, size)
    glyphs, data = [], bytearray()
    for code, ch in chars or [(ord(c), c) for c in CHARS]:
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w, h = max(0, right - left), max(0, bottom - top)
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        px = img.tobytes()
        offset = len(data)
        nibbles = [v >> 4 for v in px[: w * h]]
        if len(nibbles) % 2:
            nibbles.append(0)
        data += bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
        glyphs.append((code, w, h, left, top, round(font.getlength(ch)), offset))
    return glyphs, data


def icon_chars(ttf: str) -> list:
    points = json.loads((Path(ttf).parent / "codepoints.json").read_text())
    return [(0xE000 + i, chr(points[name])) for i, name in enumerate(ICONS)]


def main() -> None:
    ttf, condensed = sys.argv[1], sys.argv[2]
    icons = icon_chars(ttf)
    out = [
        "/* Generated by tools/dbtools/gen_font.py from DejaVu Sans (Bitstream Vera license) and Lucide (ISC).",
        " * Do not edit. */",
        '#include "font.h"',
        "",
    ]
    jobs = [(name, path.format(condensed=condensed), size, None) for name, path, size in FONTS]
    jobs += [(n, ttf, size, icons) for n, size in ICON_FONTS]
    for name, path, size, chars in jobs:
        glyphs, data = render(path, size, chars)
        out.append(f"static const uint8_t {name}_bits[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
        out.append("};")
        out.append(f"static const ui_glyph_t {name}_glyphs[] = {{")
        out += [f"    {{{c}, {w}, {h}, {x}, {y}, {a}, {o}}}," for c, w, h, x, y, a, o in glyphs]
        out.append("};")
        out.append(f"const ui_font_t ui_font_{name} = {{{len(glyphs)}, {name}_glyphs, {name}_bits}};")
        out.append("")
    OUT.write_text("\n".join(out))
    header = [
        "/* Generated by tools/dbtools/gen_font.py. Icons as UTF-8 strings for ui_text with an icon font. */",
        "#pragma once",
        "",
    ]
    width = max(len(m) for m in ICONS.values())
    for i, macro in enumerate(ICONS.values()):
        cp = 0xE000 + i
        utf8 = "".join(f"\\x{b:02x}" for b in chr(cp).encode())
        header.append(f'#define ICON_{macro:<{width}} "{utf8}"')  # aligned like clang-format wants
    (HERE / "icons.h").write_text("\n".join(header) + "\n")
    print(f"wrote {OUT} and icons.h")


if __name__ == "__main__":
    main()
